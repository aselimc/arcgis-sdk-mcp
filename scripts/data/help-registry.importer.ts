/**
 * What each import rule of design section 4.6 produces. `ruleFor` (`help-registry.rules.ts`)
 * picks the rule of an entry; the `Importer` applies it. Pure: no I/O, no clock.
 */
import type { AnySourceDef, Product } from '../../src/core/types.js';
import { proCatalog, proSourceBooks } from './help-registry.pro.js';
import type { HelpRegistry, ImportRule, LedgerRow } from './help-registry.rules.js';
import type { Entry, RulesFile, SourceFile } from './help-registry.schema.js';
import {
  LATEST_LINE,
  bookList,
  compareVersionsDesc,
  docfxSource,
  legacyHelpSource,
  officialName,
  versionLine,
} from './help-registry.sources.js';
import { findProblems } from './help-registry.validate.js';

/** The keys of a product in the order of the `Product` interface, which is how the module lists them. */
const PRODUCT_KEYS = [
  'id',
  'name',
  'aliases',
  'category',
  'tier',
  'status',
  'statusNote',
  'successor',
  'summary',
  'keywords',
  'languages',
  'homepage',
  'packages',
  'repos',
  'lines',
  'sources',
  'oracles',
  'esearch',
  'startHere',
  'pitfalls',
  'related',
  'licenseTier',
  'verifiedOn',
] as const satisfies ReadonlyArray<keyof Product>;

/** Rules add fields in the order they learn them; the generated module should not show that. */
function inDeclarationOrder(product: Product): Product {
  const known: readonly string[] = PRODUCT_KEYS;
  const unknown = Object.keys(product).filter((key) => !known.includes(key));
  if (unknown.length > 0) {
    throw new Error(`${product.id}: PRODUCT_KEYS does not list ${unknown.join(', ')}`);
  }
  const ordered: Partial<Record<keyof Product, unknown>> = {};
  for (const key of PRODUCT_KEYS) {
    if (product[key] !== undefined) ordered[key] = product[key];
  }
  // Same keys and values as `product`, re-inserted in a fixed order.
  return ordered as Product;
}

/** The source id of a `product/source` target. */
function sourceIdOf(target: string): string {
  const [product, sourceId, ...rest] = target.split('/');
  if (!product || !sourceId || rest.length > 0) {
    throw new Error(`"${target}" is not of the form product/source`);
  }
  return sourceId;
}

/** Mutable state of one import run: pass 1 (`create`), pass 2 (`attach`), then `finish`. */
export class Importer {
  readonly products = new Map<string, Product>();
  readonly developerSources: Record<string, AnySourceDef> = {};
  readonly developerLinks: Record<string, { title: string; ref: string }> = {};
  readonly ledger: LedgerRow[] = [];
  /** Product id -> version -> access, for the numbered lines its legacy sources need. */
  private readonly versions = new Map<string, Map<string, 'live' | 'link-only'>>();
  private readonly usedMeta = new Set<string>();
  /** Tombstones whose own pages are gone: `finish` links them to their related products. */
  private readonly unreachableTombstones = new Set<string>();

  constructor(
    private readonly source: SourceFile,
    private readonly rules: RulesFile,
  ) {}

  /** The id a rule's map assigns to an entry; a missing mapping is an error, not a default. */
  private mapped(map: Record<string, string>, entry: Entry, mapName: string): string {
    const target = map[entry.id];
    if (target === undefined) throw new Error(`${entry.id}: no entry in rules.${mapName}`);
    return target;
  }

  private product(id: string, forEntry: Entry): Product {
    const product = this.products.get(id);
    if (product === undefined) {
      throw new Error(`${forEntry.id}: target product ${id} is not generated by any entry`);
    }
    return product;
  }

  private record(entry: Entry, rule: ImportRule, target: string): void {
    this.ledger.push({ entry: entry.id, rule, target });
  }

  /** Fields every generated product shares; `id` selects this project's wording for it. */
  private base(
    id: string,
    entry: Entry,
  ): Omit<Product, 'tier' | 'status' | 'homepage' | 'sources'> {
    const meta = this.rules.products[id];
    if (meta === undefined) throw new Error(`${entry.id}: rules.products has no "${id}"`);
    if (this.products.has(id)) throw new Error(`${entry.id}: product ${id} is generated twice`);
    this.usedMeta.add(id);
    return {
      id,
      name: meta.name ?? officialName(entry.name),
      // The URL slug is what people copy from a help link; a developer id is never shadowed.
      aliases:
        entry.url_slug === id || this.rules.developerIds.includes(entry.url_slug)
          ? []
          : [entry.url_slug],
      category: 'product-help',
      ...(meta.statusNote === undefined ? {} : { statusNote: meta.statusNote }),
      ...(meta.successor === undefined ? {} : { successor: meta.successor }),
      summary: meta.summary,
      keywords: meta.keywords,
      languages: [],
      packages: [],
      repos: [],
      lines: [LATEST_LINE],
      oracles: [],
      startHere: [],
      pitfalls: meta.pitfalls ?? [],
      related: meta.related ?? [],
      licenseTier: 'esri-website-terms',
      verifiedOn: this.source.generated,
    };
  }

  private addVersions(productId: string, versions: string[], live: string[] = versions): void {
    const known = this.versions.get(productId) ?? new Map<string, 'live' | 'link-only'>();
    for (const version of versions) {
      // A version one source can fetch stays live even where another source only links to it.
      if (known.get(version) !== 'live') {
        known.set(version, live.includes(version) ? 'live' : 'link-only');
      }
    }
    this.versions.set(productId, known);
  }

  /** Pass 1: entries that become a product of their own. */
  create(entry: Entry, rule: ImportRule): boolean {
    switch (rule) {
      case 'docesri-product':
        this.docesriProduct(entry);
        return true;
      case 'standalone-help':
      case 'standalone-link':
        this.standaloneProduct(entry, rule);
        return true;
      case 'tombstone':
        this.tombstone(entry);
        return true;
      default:
        return false;
    }
  }

  private docesriProduct(entry: Entry): void {
    const id = entry.url_slug;
    const base = this.base(id, entry);
    const excluded = id === this.rules.pro.product ? this.rules.pro.docfxExcludedBooks : [];
    const sections = bookList(entry)
      .map((book) => book.path)
      .filter((path) => !excluded.includes(path));
    this.products.set(id, {
      ...base,
      tier: entry.scope.startsWith('full') ? 'help' : 'link',
      status: 'active',
      homepage: entry.base_url,
      sources: [docfxSource(entry, base.name, sections, excluded.length === 0)],
      oracles: [{ type: 'docesri-sitemap', options: { slug: id }, provides: ['documented'] }],
      esearch: {
        index: 'esri_docs_main_v1',
        site: entry.search.site,
        products: entry.search.product,
      },
      startHere: [{ title: `${base.name} help`, ref: entry.base_url }],
    });
    this.record(entry, 'docesri-product', id);
  }

  private standaloneProduct(entry: Entry, rule: 'standalone-help' | 'standalone-link'): void {
    const id = this.mapped(this.rules.standalone, entry, 'standalone');
    const base = this.base(id, entry);
    const split = this.rules.splitBooks[entry.id] ?? {};
    const books = bookList(entry).filter((book) => !Object.hasOwn(split, book.path));
    for (const [path, target] of Object.entries(split)) {
      const moved = bookList(entry).filter((book) => book.path === path);
      const title = `${base.name}: ${path}`;
      this.developerSources[target] = legacyHelpSource({
        id: sourceIdOf(target),
        title,
        entry,
        books: moved,
        floor: true,
      });
    }
    const help = legacyHelpSource({
      id: 'help',
      title: `${base.name} help`,
      entry,
      books,
      floor: true,
    });
    // Product roots on this host redirect to marketing pages; a book root is always reachable.
    const homepage = `${entry.base_url}${books[0]?.path ?? ''}/`;
    this.products.set(id, {
      ...base,
      tier: rule === 'standalone-help' ? 'help' : 'link',
      status: 'active',
      homepage,
      sources: [help],
      esearch: {
        site: entry.search.site,
        products: entry.search.product,
        // Numbered copies of a page exist next to /latest/; only the alias is current.
        ...(entry.base_url.includes('/latest/') ? { keepUrl: '/latest/' } : {}),
      },
      startHere: [
        { title: `${base.name} help`, ref: homepage },
        ...(id === 'arcgis-online' ? this.onlineStartHere(entry) : []),
      ],
    });
    this.record(entry, rule, id);
  }

  /** The developer-facing pages of the ArcGIS Online help that the research singled out. */
  private onlineStartHere(entry: Entry): Product['startHere'] {
    return this.rules.onlineStartHere.map(({ group, title }) => {
      const pages = this.source.arcgis_online_developer_pages[group];
      const page = Array.isArray(pages) ? pages[0] : undefined;
      if (page === undefined)
        throw new Error(`rules.onlineStartHere: no research group "${group}"`);
      return { title, ref: `${entry.base_url}${page}` };
    });
  }

  private tombstone(entry: Entry): void {
    const id = this.mapped(this.rules.tombstones, entry, 'tombstones');
    const base = this.base(id, entry);
    // The one link a tombstone offers must answer. Where the research found the old root
    // gone it names a page that is there (`landing_url`), or the help has moved to the
    // related products, whose pages `finish` links instead.
    const root =
      entry.landing_url ??
      entry.base_url.replace('<version>', entry.other_versions_on_host[0] ?? 'latest');
    // A root that redirects to a notice on another site still tells a reader what happened;
    // one that ends in an error on the documentation host itself tells nothing.
    const endsOnHost = (entry.root_redirect ?? '').startsWith(`https://${entry.host}/`);
    if (
      entry.landing_url === undefined &&
      endsOnHost &&
      (entry.root_final_status ?? 200) >= 400
    ) {
      this.unreachableTombstones.add(id);
    }
    const notice = entry.root_redirect ?? '';
    this.products.set(id, {
      ...base,
      // A tombstone is found by its exact id only; a slug alias could shadow a live product.
      aliases: [],
      tier: 'link',
      status: 'retired',
      homepage: root,
      lines: [{ ...LATEST_LINE, label: 'Retired', access: 'link-only' }],
      sources: [],
      startHere: [
        { title: `${base.name} help (retired)`, ref: root },
        ...(notice.startsWith('https://support.esri.com/')
          ? [{ title: 'Deprecation notice', ref: notice }]
          : []),
      ],
    });
    this.record(entry, 'tombstone', id);
  }

  /** Pass 2: entries that extend a product created in pass 1, or a developer product. */
  attach(entry: Entry, rule: ImportRule): void {
    const { rules } = this;
    switch (rule) {
      case 'saas-twin': {
        const product = this.product(this.mapped(rules.saasTwins, entry, 'saasTwins'), entry);
        const title = `${product.name} help (ArcGIS Online, on ${entry.host})`;
        product.sources.push(
          legacyHelpSource({ id: 'saas', title, entry, books: bookList(entry) }),
        );
        return this.record(entry, rule, `${product.id}/saas`);
      }
      case 'developer-books': {
        const target = this.mapped(rules.developerBooks, entry, 'developerBooks');
        this.developerSources[target] = legacyHelpSource({
          id: sourceIdOf(target),
          title: `${officialName(entry.name)} help`,
          entry,
          books: bookList(entry),
          floor: true,
        });
        return this.record(entry, rule, target);
      }
      case 'migrated-alias': {
        const product = this.product(
          this.mapped(rules.migratedAliases, entry, 'migratedAliases'),
          entry,
        );
        if (entry.url_slug !== product.id && !product.aliases.includes(entry.url_slug)) {
          product.aliases.push(entry.url_slug);
        }
        return this.record(entry, rule, product.id);
      }
      case 'developer-tombstone-link': {
        const target = this.mapped(rules.developerTombstoneLinks, entry, 'developerTombstoneLinks');
        const book = bookList(entry)[0]?.path ?? '';
        this.developerLinks[target] = {
          title: `${officialName(entry.name)} help (retired)`,
          ref: `${entry.base_url}${book}/`,
        };
        return this.record(entry, rule, target);
      }
      case 'enterprise-legacy-lines':
        return this.legacySource(entry, rule, rules.enterpriseProduct, `legacy-${entry.url_slug}`);
      case 'migrated-legacy':
        return this.legacySource(
          entry,
          rule,
          this.mapped(rules.migratedLegacy, entry, 'migratedLegacy'),
          'legacy',
        );
      case 'pro-legacy-lines':
        return this.proLegacy(entry);
      default:
        throw new Error(`${entry.id}: rule ${rule} was not handled in pass 1`);
    }
  }

  private legacySource(entry: Entry, rule: ImportRule, productId: string, sourceId: string): void {
    const product = this.product(productId, entry);
    const versions = [...entry.other_versions_on_host].sort(compareVersionsDesc);
    product.sources.push(
      legacyHelpSource({
        id: sourceId,
        title: `${officialName(entry.name)} help, earlier versions`,
        entry,
        books: bookList(entry),
        versions,
      }),
    );
    this.addVersions(productId, versions);
    this.record(entry, rule, `${productId}/${sourceId}`);
  }

  /**
   * pro.arcgis.com: two fetchable versions, older ones as links. The end-user help stays
   * with the product; the ArcPy and tool-reference books go to the developer product the
   * rules name (see `help-registry.pro.ts` for how books become sources).
   */
  private proLegacy(entry: Entry): void {
    const { product: productId, liveLines } = this.rules.pro;
    const product = this.product(productId, entry);
    const versions = [...entry.other_versions_on_host].sort(compareVersionsDesc);
    const catalog = proCatalog(entry, liveLines[0] ?? '');
    for (const [target, books] of proSourceBooks(entry, catalog, this.rules.pro)) {
      const rule = this.rules.pro.sources[target];
      if (rule === undefined) continue;
      const source = legacyHelpSource({
        entry,
        versions,
        liveVersions: liveLines,
        id: sourceIdOf(target),
        title: rule.title,
        books,
        probeBook: rule.probeBook,
      });
      if (target.startsWith(`${productId}/`)) product.sources.push(source);
      else this.developerSources[target] = source;
    }
    this.addVersions(productId, versions, liveLines);
    this.record(entry, 'pro-legacy-lines', `${productId}/legacy`);
  }

  /** Points a tombstone whose own pages are gone at the help of the products that replaced it. */
  private linkToRelated(id: string): void {
    const product = this.products.get(id);
    if (product === undefined) return;
    const heirs = product.related
      .map((related) => this.products.get(related))
      .filter((heir): heir is Product => heir !== undefined);
    const [first] = heirs;
    if (first === undefined) {
      throw new Error(
        `${id}: its root no longer answers; the research entry needs landing_url, or rules.products.${id}.related a generated product`,
      );
    }
    product.homepage = first.homepage;
    product.startHere = heirs.map((heir) => ({ title: `${heir.name} help`, ref: heir.homepage }));
  }

  /** Gives products with legacy sources their numbered lines and pins other sources to `latest`. */
  finish(): HelpRegistry {
    for (const [productId, versions] of this.versions) {
      const product = this.products.get(productId);
      if (product === undefined) continue;
      // Labels are the bare version: messages write them after the product name
      // ("ArcGIS Pro 3.4 pages are not fetched").
      product.lines = [
        LATEST_LINE,
        ...[...versions.keys()]
          .sort(compareVersionsDesc)
          .map((version) => versionLine(version, versions.get(version) ?? 'link-only')),
      ];
      product.sources = product.sources.map((source) =>
        source.lines === undefined ? { ...source, lines: [LATEST_LINE.id] } : source,
      );
    }
    for (const id of this.unreachableTombstones) this.linkToRelated(id);
    const registry: HelpRegistry = {
      products: [...this.products.values()].map(inDeclarationOrder),
      developerSources: this.developerSources,
      developerLinks: this.developerLinks,
      ledger: this.ledger,
    };
    const problems = findProblems(registry, this.source, this.rules, this.usedMeta);
    if (problems.length > 0) throw new Error(`Help import failed:\n- ${problems.join('\n- ')}`);
    return registry;
  }
}
