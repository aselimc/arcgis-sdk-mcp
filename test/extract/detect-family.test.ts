import { describe, expect, it } from 'vitest';
import type { HtmlFamily } from '../../src/core/types.js';
import { detectFamily } from '../../src/extract/index.js';

const page = (body: string, head = ''): string =>
  `<!doctype html><html><head>${head}</head><body>${body}</body></html>`;

const GATSBY = '<meta name="generator" content="Gatsby 5.14.1">';
const ASTRO_ASSET = '<link rel="stylesheet" href="/x/_astro/base.css">';

describe('detectFamily', () => {
  const cases: Array<[HtmlFamily, string, string]> = [
    ['documentx', 'the body container', page('<div id="i-body-content"></div>')],
    ['dartdoc', 'the main content container', page('<div id="dartdoc-main-content"></div>')],
    ['dokka', 'the pageIds attribute', page('<div id="content" class="main-content" pageIds="m::p/T///X"></div>')],
    ['dokka', 'a template command', page('<dokka-template-command data="x"></dokka-template-command>')],
    ['javadoc-legacy', 'the 1.x generator comment', `<html><head><!-- Generated by javadoc (1.8.0_322) --></head><body></body></html>`],
    ['javadoc-legacy', 'the frames-era layout', page('<div class="header"><h2 class="title">Interface X</h2></div><div class="contentContainer"></div>')],
    ['javadoc', 'the generator comment', `<html><head><!-- Generated by javadoc (21) --></head><body></body></html>`],
    ['javadoc', 'the class description section', page('<main role="main"><section class="class-description"></section></main>')],
    ['docfx-net', 'the article with a uid', page('<article id="_content" data-uid="A.B"></article>')],
    ['docfx-esri', 'the main article with a uid', page('<article id="main" data-uid="1"></article>')],
    ['support-kb', 'the article container', page('<div class="esri-technical"></div>')],
    ['qdoc', 'the QDoc container', page('<main id="main"><div class="qdoc-html"></div></main>', ASTRO_ASSET)],
    ['gatsby', 'the generator meta', page('<main id="main"></main>', GATSBY)],
    ['gatsby-rest', 'a metadata grid', page('<main id="main"><dl class="grid"></dl></main>', GATSBY)],
    ['astro', 'an island', page('<main id="main"><astro-island></astro-island></main>')],
    ['astro', 'an asset path', page('<main id="main"></main>', ASTRO_ASSET)],
    ['astro-sample', 'the hidden source block', page('<main id="main"><div class="sample-code-source"></div></main>', ASTRO_ASSET)],
    ['astro-js-ref', 'a member card', page('<main id="main"><div class="lumina-detail"></div></main>', ASTRO_ASSET)],
    ['legacy-help', 'the content section', page('<div class="content-section"><main></main></div>')],
    ['legacy-help', 'a numbered section', page('<main><section class="section1"></section></main>')],
    ['generic', 'nothing known', page('<article><h1>Hello</h1></article>')],
    ['generic', 'a main element without a known shell', page('<main id="main"><p>Hello</p></main>')],
    ['generic', 'an empty document', ''],
  ];

  it.each(cases)('detects %s by %s', (family, _marker, html) => {
    expect(detectFamily(html)).toBe(family);
  });

  it('tests QDoc before Astro, because QDoc pages sit in the Astro shell', () => {
    const html = page('<main id="main"><astro-island></astro-island><div class="qdoc-html"></div></main>', ASTRO_ASSET);
    expect(detectFamily(html)).toBe('qdoc');
  });

  it('tests the old javadoc marker before the general one', () => {
    const html = '<html><head><!-- Generated by javadoc (1.7.0_80) on a Monday --></head><body><main role="main"></main></body></html>';
    expect(detectFamily(html)).toBe('javadoc-legacy');
  });

  it('prefers the sample family over the reference family, and Gatsby over Astro', () => {
    const both = page('<main id="main"><div class="sample-code-source"></div><div class="lumina-detail"></div></main>', ASTRO_ASSET);
    expect(detectFamily(both)).toBe('astro-sample');
    expect(detectFamily(page('<main id="main"><astro-island></astro-island></main>', GATSBY))).toBe('gatsby');
  });

  it('reads the javadoc marker only from the head of the document', () => {
    const late = page(`<article>${'<p>text</p>'.repeat(400)}<!-- Generated by javadoc (21) --></article>`);
    expect(detectFamily(late)).toBe('generic');
  });
});
