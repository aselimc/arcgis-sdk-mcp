/**
 * Page family detection: first match in a fixed order. The order is load-bearing: QDoc pages
 * are embedded in the Astro shell, so they must be tested before the generic Astro rule, and
 * the old javadoc marker must be tested before the general one.
 */
import { load, type CheerioAPI } from 'cheerio';
import type { HtmlFamily } from '../core/types.js';

/** The generator comment of javadoc sits in the first lines of the document. */
const JAVADOC_HEAD_BYTES = 3072;

/** Family of an already parsed page. `html` is the same document as text. */
export function detectFamilyOf($: CheerioAPI, html: string): HtmlFamily {
  const has = (selector: string): boolean => $(selector).length > 0;
  const head = html.slice(0, JAVADOC_HEAD_BYTES);

  if (has('div#i-body-content')) return 'documentx';
  if (has('div#dartdoc-main-content')) return 'dartdoc';
  // cheerio lower-cases attribute names: the page writes `pageIds`.
  if (has('div#content.main-content[pageids]') || has('dokka-template-command')) return 'dokka';
  if (
    head.includes('Generated by javadoc (1.') ||
    (has('div.contentContainer') && has('div.header h2.title'))
  ) {
    return 'javadoc-legacy';
  }
  if (head.includes('Generated by javadoc') || has('main[role=main] section.class-description')) {
    return 'javadoc';
  }
  if (has('article#_content[data-uid]')) return 'docfx-net';
  if (has('article#main[data-uid]')) return 'docfx-esri';
  if (has('div.esri-technical')) return 'support-kb';
  if (has('div.qdoc-html')) return 'qdoc';

  if (has('main#main')) {
    const generator = ($('meta[name=generator]').attr('content') ?? '').toLowerCase();
    if (generator.startsWith('gatsby')) return has('main#main dl.grid') ? 'gatsby-rest' : 'gatsby';
    if (has('astro-island') || html.includes('/_astro/')) {
      if (has('div.sample-code-source')) return 'astro-sample';
      if (has('div.lumina-detail')) return 'astro-js-ref';
      return 'astro';
    }
  }
  if (has('div.content-section main') || has('main section.section1')) return 'legacy-help';
  return 'generic';
}

/**
 * Page types that live inside another family's site shell. A source declares the family of
 * its site (`astro`, `gatsby`); one page of that site can still be a sample, a reference
 * page or embedded QDoc output, each with a profile of its own.
 */
const REFINEMENTS: Partial<Record<HtmlFamily, readonly HtmlFamily[]>> = {
  astro: ['astro-js-ref', 'astro-sample', 'qdoc'],
  gatsby: ['gatsby-rest'],
};

/**
 * The family to convert a page as, given the family its source declares. The hint decides,
 * except that a page carrying the marker of a more specific page type of the hinted site is
 * converted as that type: without this, every sample page of an Astro site lost its source
 * files and the Qt reference kept its raw summary tables.
 */
export function resolveFamily($: CheerioAPI, html: string, hint?: HtmlFamily): HtmlFamily {
  if (hint === undefined) return detectFamilyOf($, html);
  const refinements = REFINEMENTS[hint];
  if (refinements === undefined) return hint;
  const detected = detectFamilyOf($, html);
  return refinements.includes(detected) ? detected : hint;
}

/** Family of an HTML document given as text. */
export function detectFamily(html: string): HtmlFamily {
  return detectFamilyOf(load(html), html);
}
